const DICTS = { de: DE, en: EN };

export function t(lang, key, params = []) {
  const dict = DICTS[String(lang).slice(0, 2).toLowerCase()] ?? EN;
  const s = dict[key] ?? EN[key] ?? key;
  return s.replace(/\{(\d)\}/g, (_, i) => String(params[Number(i)] ?? ''));
}

/** Alle Banner-/Dialog-Texte für das Content-Script. */
export function uiStrings(lang) {
  const dict = DICTS[String(lang).slice(0, 2).toLowerCase()] ?? EN;
  const out = {};
  // Platzhalter ({0}) bleiben stehen: das Banner setzt z. B. die Punktzahl selbst ein.
  for (const k of Object.keys(EN)) if (!k.startsWith('sig_')) out[k] = dict[k] ?? EN[k];
  return out;
}
