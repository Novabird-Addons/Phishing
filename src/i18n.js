const DICTS = { de: DE, en: EN };

export function t(lang, key, params = []) {
  const dict = DICTS[String(lang).slice(0, 2).toLowerCase()] ?? EN;
  const s = dict[key] ?? EN[key] ?? key;
  return s.replace(/\{(\d)\}/g, (_, i) => String(params[Number(i)] ?? ''));
}

